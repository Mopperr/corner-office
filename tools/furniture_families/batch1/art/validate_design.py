"""Validate Design Specialist's hh_cat_*.glb files (copy/adaptation of validate.py; validate.py untouched).

    python3 validate_design.py batch1     # writes ../../VALIDATION_design.md/.json in that batch folder
    python3 validate_design.py batch2

Same checks as validate.py, plus: every material is Principled-flat (roughness 0.82 +-0.05,
metallic 0) and has no texture slot; first colour-way aliases extended (leather -> walnut,
gilt -> brass, tin -> steel, copper never allowed).
"""
import csv, json, os, sys, importlib.util
HERE = os.path.dirname(os.path.abspath(__file__))
FAM = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
spec = importlib.util.spec_from_file_location("v", os.path.join(HERE, "validate.py"))
v = importlib.util.module_from_spec(spec); spec.loader.exec_module(v)
v.ALIAS.update({"off": "dark", "leather": "walnut", "gilt": "brass", "tin": "steel"})
CFG = json.load(open(os.path.join(HERE, "validate_design_config.json")))

def run(batch):
    out = os.path.join(FAM, batch)
    v.OUT = out
    v.FRONT = CFG["front"]
    rows = {r["family_id"]: r for r in csv.DictReader(open(os.path.join(FAM, "families.csv")))}
    res = []
    for fid in CFG[batch]:
        r = v.check(fid, rows[fid])
        b = open(os.path.join(out, r["file"]), "rb").read()
        import struct
        jl = struct.unpack("<I", b[12:16])[0]; j = json.loads(b[20:20 + jl])
        bad = []
        for m in j.get("materials", []):
            p = m.get("pbrMetallicRoughness", {})
            if abs(p.get("roughnessFactor", 1.0) - 0.82) > 0.05 or p.get("metallicFactor", 1.0) != 0 \
               or "baseColorTexture" in p or "metallicRoughnessTexture" in p or "normalTexture" in m:
                bad.append(m.get("name"))
        r["checks"]["flat_matte_r082"] = not bad
        if bad: r["notes"].append("non-flat materials: %s" % bad)
        r["pass"] = all(x is not False for x in r["checks"].values())
        res.append(r)
    json.dump({"generated_by": "_build/art/validate_design.py (Art Specialist)", "batch": batch, "files": res,
               "all_pass": all(r["pass"] for r in res)}, open(os.path.join(out, "VALIDATION_design.json"), "w"), indent=1)
    keys = list(res[0]["checks"])
    L = ["# VALIDATION - %s (Design Specialist's 10, validated by Art Specialist)" % batch, "",
         "Created by Andrew's Helpers (Grok Bots)", "",
         "Generated by `batch1/_build/art/validate_design.py` (adapted copy of `validate.py`). glTF Y-up: w = X, h = Y, d = Z.",
         "PASS = ok, FAIL = not to spec, n/a = not applicable.", "",
         "| file | w x d x h (actual) | CSV | max dev | KB | " + " | ".join(keys) + " | result |",
         "|---|---|---|---|---|" + "---|" * len(keys) + "---|"]
    for r in res:
        s, c = r["size_m"], r["csv_m"]
        L.append("| %s | %.3f x %.3f x %.3f | %.2f x %.2f x %.2f | %.2f%% | %.0f | %s | **%s** |" % (
            r["file"], s["w"], s["d"], s["h"], c["w"], c["d"], c["h"], r["max_size_deviation_pct"],
            r["size_bytes"] / 1024, " | ".join({True: "PASS", False: "FAIL", None: "n/a"}[r["checks"][k]] for k in keys),
            "PASS" if r["pass"] else "FAIL"))
    L += ["", "## Notes", ""]
    for r in res:
        L.append("- **%s**: way %s (expected %s from '%s'); materials: %s; %s" % (
            r["family_id"], r["way_colour"]["actual"], r["way_colour"]["expected"], r["way_colour"]["colourway"],
            ", ".join(r["materials"]), "; ".join(r["notes"])))
    L += ["", "Overall: **%s** (%d/%d files pass)" % ("ALL PASS" if all(r["pass"] for r in res) else "SOME FAIL",
                                                     sum(r["pass"] for r in res), len(res))]
    open(os.path.join(out, "VALIDATION_design.md"), "w").write("\n".join(L) + "\n")
    for r in res:
        print(batch, r["family_id"], "PASS" if r["pass"] else "FAIL", r["max_size_deviation_pct"],
              {k: x for k, x in r["checks"].items() if x is not True}, r["notes"][0][:80])
    return res

if __name__ == "__main__":
    for b in (sys.argv[1:] or ["batch1", "batch2"]):
        run(b)
